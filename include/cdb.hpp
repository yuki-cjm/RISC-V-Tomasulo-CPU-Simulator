#pragma once

#include "type.h"

// ============================================================================
// CDB_Entry: 公共数据总线上的广播条目
// ============================================================================
struct CDB_Entry {
    bool valid;          // 本周期是否有广播
    u32  value;          // 广播的值
    int  tag;            // 生产者标签
    bool mispredicted;   // 分支预测失败
    u32  correct_pc;     // 预测失败时的正确 PC
    int  branch_rob;     // 分支在 ROB 中的索引（用于 flush）
};

// ============================================================================
// CDB: 公共数据总线，每周期最多广播一个结果
//
// 使用方式：
//   1. 每周期开始时，CPU 从所有部件的旧状态中 precompute_cdb()
//   2. 四个步骤（issue/execute/writeback/commit）都使用这个 CDB
//   3. 各步骤通过 CDB 获取操作数旁路、分支结果、mispredict 信息
// ============================================================================
CDB_Entry make_empty_cdb();
